-- Match PanelV2's learned-spell check through the addon's existing API.
local function isKnown(spellID)
  local aliases = WowBuddyDev.classes[1485].spellReadyAliases
  for _, id in ipairs(aliases[spellID] or { spellID }) do
    local ok, known = pcall(WowBuddyDev.IsSpellKnown, id)
    if ok and known == true then return true end
  end
  return false
end

