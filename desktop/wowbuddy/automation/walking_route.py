def _auberdine_ramp_height(index):
    left = min(math.floor(index), len(_AUBERDINE_DESCENT_PROFILE) - 2)
    start, end = (_AUBERDINE_DESCENT_PROFILE[i][2] for i in (left, left + 1))
    return start + (end - start) * (index - left)


def auberdine_overlapping_floor(x, y):
    return x is not None and y is not None and x < 36.74 and 45.02 <= y <= 46.12


def _darkshore_road_position(x, y, *, limit=65, elevation=None):
    if elevation is not None:
        descent = _road_position(_AUBERDINE_DESCENT, x, y, scale=_DARKSHORE_YARDS, limit=min(limit, .85))
        if descent is not None and abs(elevation - _auberdine_ramp_height(descent[0])) <= .75:
            return _AUBERDINE_DESCENT, descent
    # 平台与坡道下方和上方共用平面坐标，这片区域不直接接入镇内道路。
    if auberdine_overlapping_floor(x, y):
        return None
    harbor = _road_position(_AUBERDINE_HARBOR_ROAD, x, y, scale=_DARKSHORE_YARDS, limit=min(limit, 2))
    if harbor is not None and harbor[0] > 0:
        return _AUBERDINE_HARBOR_ROAD, harbor
    rejoin = _road_position(_DARKSHORE_SOUTH_TIGER_REJOIN, x, y, scale=_DARKSHORE_YARDS, limit=min(limit, 4))
    if rejoin is not None:
        return _DARKSHORE_SOUTH_TIGER_REJOIN, rejoin
    roads = (_DARKSHORE_CAMP_ROAD, *(road for road, (parent, _) in _DARKSHORE_BRANCHES.items()
                                   if parent is _DARKSHORE_CAMP_ROAD))
    match = _closest_road_position(roads, x, y,
                                   scale=_DARKSHORE_YARDS, limit=limit)
    return _wide_road_match(match, 1439, x, y, _DARKSHORE_YARDS, 7)


