def _road_position(road, x, y, *, scale=(1, 1), limit=0.85):
    if x is None or y is None:
        return None
    nearest = None
    best_distance = limit
    sx, sy = scale
    for index, ((ax, ay), (bx, by)) in enumerate(zip(road, road[1:])):
        dx, dy = (bx - ax) * sx, (by - ay) * sy
        if dx == dy == 0:
            continue
        along = min(1, max(0, ((x - ax) * sx * dx + (y - ay) * sy * dy) / (dx * dx + dy * dy)))
        point = (ax + along * (bx - ax), ay + along * (by - ay)) if 0 < along < 1 else road[index + int(along)]
        distance = math.hypot((x - point[0]) * sx, (y - point[1]) * sy)
        if distance <= best_distance:
            nearest = index + along, point
            best_distance = distance
    return nearest


