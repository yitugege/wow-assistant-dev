def _road_chain(road, location, branches):
    approach = ()
    chain = {road: (location, approach)}
    while road in branches:
        parent, junction = branches[road]
        approach += _road_between(road, location, (road.index(junction), junction))[:-1]
        road, location = parent, (parent.index(junction), junction)
        chain[road] = location, approach
    return chain


