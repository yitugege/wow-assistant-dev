def _ashenvale_north_join(start, end):
    if start is None or end is None:
        return ()
    main = _ASHENVALE_NORTH_ROAD
    from_road, source = start
    to_road, target = end
    if from_road == to_road:
        return _road_between(from_road, source, target)
    prefix = suffix = ()
    if from_road != main:
        entry = from_road[0]
        prefix = _road_between(from_road, source, (0, entry))[:-1]
        source = main.index(entry), entry
    if to_road != main:
        entry = to_road[0]
        suffix = _road_between(to_road, (0, entry), target)[1:]
        target = main.index(entry), entry
    return prefix + _road_between(main, source, target) + suffix


def _ashenvale_north_entry(position, *, limit):
    if position is None:
        return _ASHENVALE_NORTH_ROAD, (0, _ASHENVALE_NORTH_ROAD[0])
    return _ashenvale_north_position(*position, limit=limit)


