def camp_travel_distance(map_id, x, y, target_x, target_y):
    point = target_x, target_y
    waypoints = ()
    if map_id == 1424:
        waypoints = _hillsbrad_camp_road(MapDestination(map_id, *point, 'alive', ''), origin=(x, y))
    elif map_id == 1433:
        waypoints = _redridge_camp_road(MapDestination(map_id, *point, 'alive', ''), origin=(x, y))
    elif map_id == 1438:
        waypoints = _teldrassil_camp_road(MapDestination(map_id, *point, 'alive', ''), (x, y))
    elif map_id == 1439:
        waypoints = _darkshore_camp_road(MapDestination(map_id, *point, 'alive', ''), origin=(x, y))
    elif map_id == 1440 and point in _ASHENVALE_NORTH_CAMP_POINTS:
        waypoints = _ashenvale_north_camp_road(point, (x, y))
    elif corridor := _CAMP_CORRIDORS.get(map_id):
        road, camps = corridor
        if point in camps and (start := _road_position(road, x, y)):
            waypoints = _road_between(road, start, (camps[point], point))
    if waypoints:
        return sum(math.hypot(bx - ax, (by - ay) * 2 / 3)
                   for (ax, ay), (bx, by) in zip(waypoints, waypoints[1:]))
    return math.hypot(target_x - x, target_y - y)


def _road_between(road, start, end):
    if start == end:
        return (end[1],)
    if start[0] > end[0]:
        return _road_between(road, end, start)[::-1]
    return (start[1], *road[math.floor(start[0]) + 1:math.ceil(end[0])], end[1])


def loch_corpse_road(goal, *, origin=None):
    """东岸已核对的跑尸走廊，无起点时从湿地进图一侧接入。"""
    if (goal.map_id != 1432 or goal.life != 'ghost' or goal.x < _LOCH_DAM_DECK[-1][0]
            or (origin is not None and origin.map_id != goal.map_id)):
        return ()
    matches = [(road, end) for road in _LOCH_CORPSE_ROADS
               if (end := _road_position(road, goal.x, goal.y, scale=_LOCH_YARDS, limit=25))]
    if not matches:
        return ()
    def distance(match):
        x, y = match[1][1]
        return math.hypot((goal.x - x) * _LOCH_YARDS[0], (goal.y - y) * _LOCH_YARDS[1])

    road, end = min(matches, key=distance)
    if origin is None:
        return _road_between(road, (0, road[0]), end)
    start = _road_position(road, origin.x, origin.y, scale=_LOCH_YARDS, limit=25)
    if start is not None:
        return _road_between(road, start, end)
    junction = road.index(_LOCH_NORTH_ROAD[-2])
    road = _LOCH_GRAVEYARD_TO_DAM + road[junction:]
    start = _road_position(road, origin.x, origin.y, scale=_LOCH_YARDS, limit=25)
    if start is None:
        return ()
    end = end[0] + len(_LOCH_GRAVEYARD_TO_DAM) - junction, end[1]
    return _road_between(road, start, end)


def _corridor_camp_road(goal, origin=None, *, entry_index=0):
    road, camp_indices = _CAMP_CORRIDORS[goal.map_id]
    point = goal.x, goal.y
    if goal.life == 'ghost':
        end = _road_position(road, *point)
    elif point in camp_indices:
        end = camp_indices[point], point
    else:
        return ()
    if end is None:
        return ()
    if origin is None:
        index = entry_index % len(road)
        return _road_between(road, (index, road[index]), end)
    position = origin.x, origin.y
    start = _road_position(road, *position)
    if goal.life == 'ghost':
        for spur in _CAMP_GRAVEYARD_ROADS.get(goal.map_id, ()):
            spur_start = _road_position(spur, *position)
            if spur_start and (not start or math.dist(position, spur_start[1]) < math.dist(position, start[1])):
                join = len(spur) - 1, spur[-1]
                junction = road.index(spur[-1]), spur[-1]
                return _road_between(spur, spur_start, join)[:-1] + _road_between(road, junction, end)
    return _road_between(road, start, end) if start else ()


def _wide_road_match(match, map_id, x, y, scale, narrow_max):
    """最近路段落在窄路点、且离当前位置超过 narrow_max 码时视为不可接入，返回 None。"""
    if match is not None:
        _, (_, point) = match
        if _narrow_road_point(map_id, point) and math.hypot((point[0] - x) * scale[0],
                                                             (point[1] - y) * scale[1]) > narrow_max:
            return None
    return match


def _closest_road_position(roads, x, y, *, scale, limit):
    sx, sy = scale
    matches = [(road, location) for road in roads
               if (location := _road_position(road, x, y, scale=scale, limit=limit)) is not None]
    return min(matches, default=None, key=lambda match: math.hypot(
        (match[1][1][0] - x) * sx, (match[1][1][1] - y) * sy))


