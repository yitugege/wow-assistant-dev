@dataclass(frozen=True, slots=True)
class WalkingLeg:
    source: int
    destination: int
    level: int
    points: tuple[tuple[float, float], ...]
    # 接入同一个路口的支路与主路共用最后一段。
    approaches: tuple[tuple[tuple[float, float], ...], ...] = ()
    arrival_road: tuple[tuple[float, float], ...] = ()
    manual: bool = False
    source_name: str = ''
    destination_name: str = ''
    alliance_only: bool = False
    portal: bool = False
    taxi: bool = False

    @property
    def road_key(self):
        entry = self.arrival_road[0] if self.arrival_road else (-1, -1)
        return self.source, self.destination, self.manual, *self.points[-1], *entry

    @property
    def blocked_key(self):
        roads = (self.points, *self.approaches, self.arrival_road)
        coordinates = [[(float(x), float(y)) for x, y in road] for road in roads]
        digest = sha256(json.dumps(coordinates, separators=(',', ':')).encode('ascii')).hexdigest()
        return (*self.road_key, digest)


