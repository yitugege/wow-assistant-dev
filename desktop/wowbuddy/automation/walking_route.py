def plan_quest_approach(session, pin, position, character, *, routes=(), connections=()):
    """沿可接入的陆路前往交任务标记。跨图要求出口与目标路点连通。"""
    if (character.life != 'alive' or not character.outdoors or position.life != 'alive'
            or character.map_id != position.map_id or character.level is None):
        return None
    goal = MapDestination(pin.map_id, pin.x, pin.y, 'alive', f'任务 #{pin.quest_id} 交付点',
                          radius=4, allow_detour=False)
    routes = tuple(route for route in routes if route.map_id == pin.map_id and route.endpoint == (pin.x, pin.y))
    legs = ()
    if pin.map_id != position.map_id:
        road = ()
        for route in routes:
            legs = plan_walking_route(position.map_id, pin.map_id, character.level, 'alive',
                                      connections=connections, origin=(position.x, position.y),
                                      blocked_legs=source_road_blocks(position.map_id, position.x, position.y,
                                                                      elevation=position.elevation),
                                      faction=character.faction, destination_xy=route.points[0])
            if legs and legs[-1].arrival_road and not legs[-1].portal:
                end = tuple(round(value, 2) for value in legs[-1].arrival_road[-1])
                if end == route.points[0]:
                    road = route.points
                    break
        if not road:
            return None
    elif goal.contains(position):
        road = ((pin.x, pin.y),)
    else:
        scale = position.width / 100, position.height / 100
        road = camp_access_road(goal, origin=position)
        if not road:
            for route in routes:
                start = _road_position(route.points, position.x, position.y, scale=scale, limit=6)
                if start is not None:
                    road = _road_between(route.points, start, (len(route.points) - 1, route.endpoint))
                    break
        if not road:
            return None
        x, y = road[-1]
        if math.hypot((pin.x - x) * scale[0], (pin.y - y) * scale[1]) > goal.arrival_radius:
            return None
    return WalkingTrip(session, legs, goal, level=character.level, faction=character.faction,
                       camp_road=road, connections=connections, catalog_goal=goal,
                       arrival_message='已走完任务交付点的接入道路。')


