def _branched_camp_road(goal, start_location, camp_roads, branches, road_position):
    point = goal.x, goal.y
    if goal.life == 'ghost':
        end_location = road_position(*point)
    else:
        road = camp_roads.get(point)
        end_location = (road, (road.index(point), point)) if road else None
    if start_location is None or end_location is None:
        return ()
    start_road, start = start_location
    end_road, end = end_location
    if start_road == end_road:
        return _road_between(start_road, start, end)
    from_origin = _road_chain(start_road, start, branches)
    from_goal = _road_chain(end_road, end, branches)
    shared_road = next(road for road in from_origin if road in from_goal)
    start, prefix = from_origin[shared_road]
    end, reverse_suffix = from_goal[shared_road]
    return prefix + _road_between(shared_road, start, end) + reverse_suffix[::-1]


