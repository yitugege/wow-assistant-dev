def camp_scan_waypoint(camp, position, *, manual_road=()):
    """用已经走过的接入末段补扫一次，不跨桥或离开道路绕行。"""
    if not position.continuous or position.moving or not camp.contains(position):
        return None
    endpoint = camp.x, camp.y
    road = manual_road
    scout = None
    if not road:
        road = (_WESTFALL_DAGGER_ROAD if camp.map_id == 1436 and endpoint == _WESTFALL_DAGGER_HILLS
                else camp_access_road(camp))
        if camp.map_id == 1433 and endpoint == _REDRIDGE_POACHER_CAMP:
            # 只退到已走过的西侧位置，避免重新经过北面的受阻转角。
            scout = _REDRIDGE_POACHER_SCOUT
    if len(road) < 2 or road[-1] != endpoint:
        return None
    segment = (scout, endpoint) if scout is not None else road[-2:]
    if scout is None and any(_narrow_road_point(camp.map_id, point) for point in segment):
        return None
    scale = position.width / 100, position.height / 100
    projection = _road_position(segment, position.x, position.y, scale=scale, limit=5)
    dx, dy = segment[0][0] - camp.x, segment[0][1] - camp.y
    length = math.hypot(dx * scale[0], dy * scale[1])
    if projection is None or (1 - projection[0]) * length > 10:
        return None
    if scout is None:
        if length < 30:
            return None
        scout = camp.x + dx * 26 / length, camp.y + dy * 26 / length
    return MapDestination(camp.map_id, *scout, 'alive', '营地补扫点', radius=4, allow_detour=False)


def camp_scan_corridor_contains(camp, scout, position):
    segment = (camp.x, camp.y), (scout.x, scout.y)
    return (position.map_id == camp.map_id
            and _road_position(segment, position.x, position.y,
                               scale=(position.width / 100, position.height / 100), limit=8) is not None)


